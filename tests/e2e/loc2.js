const { chromium } = require("playwright");
const OUT = require("path").join(__dirname, "../../test-results");
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM || undefined });
  const page = await browser.newPage({ viewport: { width: 900, height: 1500 } });
  const errors = []; page.on("pageerror", (e) => { if (!/jsdelivr/.test(e.message)) errors.push(e.message); });
  page.on("dialog", async (d) => { console.log("DIALOG:", d.message()); await d.accept(); });
  const check = (n, c, x = "") => console.log(`${c ? "PASS" : "FAIL"} ${n} ${x}`);
  const body = () => page.locator("body").innerText();
  await page.goto("http://localhost:10000/login", { waitUntil: "networkidle" });
  await page.getByText("Explore in Demo Mode").click(); await page.waitForTimeout(1800);
  await page.goto("http://localhost:10000/asset/new", { waitUntil: "networkidle" }); await page.waitForTimeout(1200);
  await page.getByPlaceholder("e.g. ENC-DEL-LT-014").fill("BUG-SKY-NB001");
  await page.getByPlaceholder("e.g. Dell").fill("Dell");
  await page.getByPlaceholder("e.g. Latitude 5440").fill("Latitude 3420");
  await page.getByPlaceholder("e.g. C02G1234MD6R").fill("SN-123");
  await page.getByPlaceholder("0", { exact: true }).fill("50000");
  await page.getByPlaceholder("2027-01-15", { exact: true }).fill("2028-01-01");
  await page.getByText("CREATE ASSET").click(); await page.waitForTimeout(500);
  check("no site -> validation error", (await body()).includes("Please select a Location"));
  await page.getByLabel("Location *").click(); await page.getByText("BUG — Bhogapuram", { exact: true }).click();
  await page.getByPlaceholder("e.g. T3 Lounge Reception").fill("Arrivals desk");
  await page.getByText("CREATE ASSET").click(); await page.waitForTimeout(500);
  check("no vertical -> validation error", (await body()).includes("Please select the Vertical"));
  await page.getByLabel("Vertical *").click(); await page.getByText("ENCALM SKYPLATES", { exact: true }).click();
  await page.getByPlaceholder("e.g. Housekeeping").fill("Operations");
  await page.getByLabel("Criticality / Asset valuation *").click(); await page.getByText("Medium", { exact: true }).click();
  await page.getByText("CREATE ASSET").click(); await page.waitForTimeout(2000);
  const p = new URL(page.url()).pathname;
  check("saved -> detail page", p.startsWith("/asset/ENC-LAP-"), p);
  const t = await body();
  check("detail shows BUG — Arrivals desk", t.includes("BUG — Arrivals desk"));
  check("detail shows Vertical ENCALM SKYPLATES", t.includes("Vertical") && t.includes("ENCALM SKYPLATES"));
  check("status New Device", t.includes("New Device"));
  await page.screenshot({ path: OUT + "/loc-detail.png", fullPage: true });
  await page.getByText("Reassign", { exact: true }).first().click(); await page.waitForTimeout(600);
  const r = await body();
  check("reassign: site dropdown prefilled BUG + detail", r.includes("BUG — Bhogapuram") && (await page.getByPlaceholder("e.g. T3 Lounge Reception").last().inputValue()) === "Arrivals desk");
  await page.screenshot({ path: OUT + "/loc-reassign.png", fullPage: true });
  // legacy free-text location -> edit requires picking a site, detail kept
  await page.goto("http://localhost:10000/", { waitUntil: "networkidle" }); await page.waitForTimeout(800);
  check("no page errors", errors.length === 0, errors.join(" | "));
  await browser.close();
})().catch((e) => { console.error("ERR", e.message); process.exit(1); });
