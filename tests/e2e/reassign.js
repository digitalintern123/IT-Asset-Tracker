const { chromium } = require("playwright");
const { mockBackend, signIn, pickPerson } = require("./mock");
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM || undefined });
  const ctx = await browser.newContext({ viewport: { width: 900, height: 1500 } });
  await ctx.addInitScript(() => { window.__mailto = []; const d = Object.getOwnPropertyDescriptor(window.Location.prototype, "href"); });
  const backend = await mockBackend(ctx);
  const page = await ctx.newPage();
  const errors = []; page.on("pageerror", (e) => { if (!/jsdelivr/.test(e.message)) errors.push(e.message); });
  const dialogs = []; page.on("dialog", async (d) => { dialogs.push(d.message()); await d.accept(); });
  const navs = []; page.on("framenavigated", (f) => navs.push(f.url()));
  const check = (n, c, x = "") => console.log(`${c ? "PASS" : "FAIL"} ${n} ${x}`);
  await signIn(page, "admin", "/asset/ENC-LAP-2026-0001");
  const before = await page.locator("body").innerText();
  const oldUser = (before.match(/Assigned to\s*\n\s*([^\n]+)/) || [])[1];
  console.log("old user:", oldUser, "| status line:", (before.match(/In Use|Available|New Device/) || [])[0]);
  await page.getByText("Reassign", { exact: true }).first().click(); await page.waitForTimeout(600);
  await pickPerson(page, "Neha Verma");
  await page.getByPlaceholder("e.g. Department transfer, replacement unit").fill(`Handover from ${oldUser}`);
  await page.getByText(/Confirm|Transfer|Reassign/).last().click(); await page.waitForTimeout(2000);
  check("sent for approval (approval matrix), old user not named", dialogs.some((d) => d.includes("Hand-over to Neha Verma has been sent to the IT Head")) && !dialogs.some((d) => oldUser && d.includes(oldUser)), JSON.stringify(dialogs));
  check("no mailto navigation", !navs.some((u) => u.startsWith("mailto:")), JSON.stringify(navs.filter((u) => !u.startsWith("http"))));
  let t = await page.locator("body").innerText();
  check("pending: banner + device still with old user", /APPROVAL PENDING/i.test(t) && t.includes("Hand over to: Neha Verma") && !t.includes("Awaiting confirmation from neha.verma@encalm.com"), (t.match(/CUSTODY[\s\S]{0,400}/) || [""])[0].replace(/\n/g, " | "));
  // The IT Head opens the Approve link from the email
  const reqId = await page.evaluate(() => JSON.parse(localStorage.getItem("@encalm/asset_cache_v4")).items.find((a) => a.id === "ENC-LAP-2026-0001").approvalRequest.id);
  // A technician who gets hold of the link can't approve
  await signIn(page, "technician", `/approve?asset=ENC-LAP-2026-0001&request=${reqId}`);
  check("technician can't approve", (await page.locator("body").innerText()).includes("Only IT-Asset Approver members can approve") && (await page.getByRole("button", { name: "Approve", exact: true }).count()) === 0);
  await signIn(page, "admin", `/approve?asset=ENC-LAP-2026-0001&request=${reqId}&decision=approve`);
  t = await page.locator("body").innerText();
  check("approve page shows the hand-over", t.includes("Approve this hand-over?") && t.includes("Neha Verma (neha.verma@encalm.com)") && t.includes(oldUser));
  await page.getByRole("button", { name: "Approve", exact: true }).click(); await page.waitForTimeout(2000);
  check("decision recorded", (await page.locator("body").innerText()).includes("Decision recorded"));
  await page.waitForTimeout(500);
  const confirmMail = backend.mails.find((m) => m.toRecipients.some((r) => r.emailAddress.address === "neha.verma@encalm.com"));
  check("new user gets the hand-over confirmation email, old user not named", !!confirmMail && !JSON.stringify(confirmMail).includes(oldUser), JSON.stringify(backend.mails.map((m) => m.subject)));
  await page.goto("http://localhost:10000/approve?asset=ENC-LAP-2026-0001&request=" + reqId, { waitUntil: "networkidle" }); await page.waitForTimeout(1200);
  check("link can't be used twice", (await page.locator("body").innerText()).includes("no longer waiting"));
  await page.goto("http://localhost:10000/asset/ENC-LAP-2026-0001", { waitUntil: "networkidle" }); await page.waitForTimeout(1500);
  t = await page.locator("body").innerText();
  check("after approval: handed over, user asked to confirm", t.includes("Awaiting confirmation from neha.verma@encalm.com") && !/APPROVAL PENDING/i.test(t));
  check("no page errors", errors.length === 0, errors.join(" | "));
  await browser.close();
})();
