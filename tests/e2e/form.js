const { chromium } = require("playwright");
const { mockBackend, signIn } = require("./mock");
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM || undefined });
  const page = await browser.newPage({ viewport: { width: 900, height: 1800 } });
  const errors = []; page.on("pageerror", (e) => { if (!/jsdelivr/.test(e.message)) errors.push(e.message); });
  page.on("dialog", async (d) => { console.log("DIALOG:", d.message()); await d.accept(); });
  const check = (n, c, x = "") => console.log(`${c ? "PASS" : "FAIL"} ${n} ${x}`);
  const body = () => page.locator("body").innerText();
  const save = async () => { await page.getByText("CREATE ASSET").click(); await page.waitForTimeout(500); return body(); };
  await mockBackend(page.context());
  await signIn(page, "admin");
  await page.goto("http://localhost:10000/asset/new", { waitUntil: "networkidle" }); await page.waitForTimeout(1200);
  await page.getByPlaceholder("e.g. ENC-DEL-LT-014").fill("DEL-EATS-NB005");
  await page.getByPlaceholder("e.g. Dell").fill("Dell");
  await page.getByPlaceholder("e.g. Latitude 5440").fill("Latitude 3420");
  await page.getByPlaceholder("e.g. C02G1234MD6R").fill("ABC1234");
  await page.getByLabel("Location *").click(); await page.getByText("DEL — Delhi", { exact: false }).first().click();
  await page.getByLabel("Vertical *").click(); await page.getByText("ENCALM EATS PVT LTD", { exact: true }).click();
  let t = await save();
  check("Department required", t.includes("Department is required"), (t.match(/[^\n]*required[^\n]*|Please[^\n]*/) || [""])[0]);
  await page.getByPlaceholder("e.g. Housekeeping").fill("IT");
  t = await save();
  check("Criticality required", t.includes("Please select the Criticality"), (t.match(/[^\n]*required[^\n]*|Please[^\n]*/) || [""])[0]);
  await page.getByLabel("Criticality / Asset valuation *").click(); await page.getByText("High", { exact: true }).click();
  await page.getByPlaceholder("e.g. Power Cord, Bag").fill("Power Cord, Bag");
  t = await save(); await page.waitForTimeout(1500);
  const p = new URL(page.url()).pathname;
  check("saved without purchase data -> detail", p.startsWith("/asset/ENC-"), p + " " + (t.match(/Please[^\n]*|[^\n]*required[^\n]*/) || [""])[0]);
  t = await body();
  check("detail shows accessories + criticality + operational", t.includes("Power Cord, Bag") && t.includes("High") && t.includes("Operational") && t.includes("Hardware"));
  check("no page errors", errors.length === 0, errors.join(" | "));
  await browser.close();
})();
